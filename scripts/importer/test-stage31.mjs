import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { parseSitemap, canonicalizeGameUrl, discoverFromDocuments, updateDiscovery } from './discovery31.mjs';
const xml = await readFile('tests/fixtures/stage31/slots-sitemap.xml', 'utf8');
const index = await readFile('tests/fixtures/stage31/index.xml', 'utf8');
assert.equal(parseSitemap(index).kind, 'index');
assert.equal(parseSitemap(index).entries.length, 1);
const found = discoverFromDocuments([{ xml }, { xml: index }]);
assert.equal(found.length, 2);
assert.equal(canonicalizeGameUrl('https://external.example/slots/example/', 'latestcasinobonuses.bet'), null);
assert.equal(canonicalizeGameUrl('http://latestcasinobonuses.bet/slots/example/', 'latestcasinobonuses.bet'), null);
const first = updateDiscovery(null, found, '2026-10-20T00:00:00Z');
assert.equal(first.stats.added, 2);
const again = updateDiscovery(first.manifest, found, '2026-10-21T00:00:00Z');
assert.equal(again.stats.added, 0);
assert.equal(again.stats.unchanged, 2);
const modified = found.map(x => x.lastmod ? {...x, lastmod: '2026-10-21'} : x);
assert.equal(updateDiscovery(again.manifest, modified, '2026-10-22T00:00:00Z').stats.changed, 1);
console.log('Stage 31 tests OK (sitemap index, URL filters, deduplication, incremental state).');
