import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { robotsAllowed, selectPending, runPipeline } from './pipeline32.mjs';
const url='https://latestcasinobonuses.bet/slots/america-burger-bounty/';
assert.equal(robotsAllowed('User-agent: *\nDisallow: /slots/\nAllow: /slots/public/', '/slots/a/'),false);
assert.equal(robotsAllowed('User-agent: *\nDisallow: /slots/\nAllow: /slots/public/', '/slots/public/a/'),true);
assert.equal(robotsAllowed('User-agent: *\nDisallow: /', '/slots/a/'),false);
const state={schemaVersion:1,records:{a:{url,status:'new',lastmod:null},b:{url:'https://evil.example/slots/a/',status:'new'}}};
assert.equal(selectPending(state).length,1);
const dir=await mkdtemp(join(tmpdir(),'stage32-'));
const statePath=join(dir,'state.json'); const outDir=join(dir,'candidates');
await writeFile(statePath,JSON.stringify(state));
const html=resolve('tests/fixtures/lcb-america-burger-bounty.html');
const dry=await runPipeline({statePath,outDir,htmlByUrl:{[url]:html}});
assert.equal(dry.processed,1);assert.equal(dry.written,0);
const written=await runPipeline({statePath,outDir,htmlByUrl:{[url]:html},write:true});
assert.equal(written.written,1);
const after=JSON.parse(await readFile(statePath,'utf8'));
assert.equal(after.records.a.status,'fetched');
assert.equal((await runPipeline({statePath,outDir,htmlByUrl:{[url]:html}})).selected,0);
console.log('Stage 32 tests OK (robots rules, safe URL selection, dry-run, write, incremental status).');
